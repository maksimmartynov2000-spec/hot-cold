# Правила героев 451–500 (миры 46–50): (значок, правило) — правило либо on=[когда, что, раз],
# либо черты, у босса a1/a2 со своими значками. Последняя партия — 50 героев.
S = []
def r(icon, when=None, act=None, once=1, **kw):
    d = {'icon': icon}
    if when: d['on'] = [when, act, once]
    d.update(kw); S.append(d)
def boss(a1icon, a1, a2icon, a2):
    S.append({'boss': True, 'icon': '👑', 'a1icon': a1icon, 'a2icon': a2icon, 'a1': a1 + [1] if len(a1) == 2 else a1, 'a2': a2 + [1] if len(a2) == 2 else a2})
